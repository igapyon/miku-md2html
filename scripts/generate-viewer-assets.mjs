import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const generatedDir = path.join(root, 'src/ts/generated');
await mkdir(generatedDir, { recursive: true });
const css = (await readFile(path.join(root, 'src/viewer/theme.css'), 'utf8')).trimEnd();
const viewer = (await readFile(path.join(root, 'src/viewer/viewer.viewer'), 'utf8')).trim();
const source = `// Generated by scripts/generate-viewer-assets.mjs. Edit src/viewer/theme.css and viewer.viewer.\nexport const themeCss = ${JSON.stringify(css)};\nexport const viewerScript = ${JSON.stringify(viewer)};\n`;
await writeFile(path.join(generatedDir, 'viewer-assets.ts'), source, 'utf8');
